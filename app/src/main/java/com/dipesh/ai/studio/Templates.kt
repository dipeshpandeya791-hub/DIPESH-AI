/**
 * Offline project templates. Nothing here runs automatically: the output is source text the user reads,
 * edits and runs on their own computer. In template sources '§' stands for a dollar sign.
 */
object Templates {
    private fun t(s: String) = s.trimIndent().replace('§', '$') + "\n"
    private fun safeText(s: String) = s.replace(Regex("[\\u0000-\\u001F]"), " ").trim().take(300)

