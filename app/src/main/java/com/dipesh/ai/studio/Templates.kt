    private const val VIDEO_NOTE = "\n> This is a project **template** generated by DIPESH AI. DIPESH AI on your phone does not render video; run the project on a computer.\n"

    private fun remotion(n: String, d: String): FileBundle {
        val b = FileBundle(); val title = n.replace("{", "(").replace("}", ")").replace("<", "(").replace(">", ")").replace("§", "")
        b.add("README.md", "# $n (Remotion)\n\n$d\n$VIDEO_NOTE\nRemotion creates videos with React. It is free for individuals and small teams; check remotion.dev/license for company use.\n\n## Run\n```\nnpm install\nnpm run dev      # preview in the browser\nnpm run build    # renders out/video.mp4\n```\nEdit `src/Composition.tsx`.\n")
        b.add("package.json", t("""
            {
              "name": "${SafePath.slug(n)}",
              "version": "1.0.0",
              "private": true,
              "scripts": {
                "dev": "remotion studio",
                "build": "remotion render src/index.ts Main out/video.mp4"
              },
              "dependencies": {
                "@remotion/cli": "^4.0.0",
                "react": "^18.2.0",
                "react-dom": "^18.2.0",
                "remotion": "^4.0.0"
              },
              "devDependencies": {
                "@types/react": "^18.2.0",
                "typescript": "^5.0.0"
              }
            }
        """))
        b.add("tsconfig.json", t("""
            { "compilerOptions": { "target": "ES2020", "module": "ESNext", "moduleResolution": "node", "jsx": "react-jsx", "strict": true, "skipLibCheck": true }, "include": ["src"] }
        """))
        b.add("remotion.config.ts", "import { Config } from '@remotion/cli/config';\n\nConfig.setVideoImageFormat('jpeg');\n")
        b.add("src/index.ts", "import { registerRoot } from 'remotion';\nimport { Root } from './Root';\n\nregisterRoot(Root);\n")
        b.add("src/Root.tsx", t("""
            import { Composition } from 'remotion';
            import { Main } from './Composition';

            export const Root: React.FC = () => (
              <Composition id="Main" component={Main} durationInFrames={150} fps={30} width={1080} height={1920} />
            );
        """))
        b.add("src/Composition.tsx", t("""
            import { AbsoluteFill, interpolate, spring, useCurrentFrame, useVideoConfig } from 'remotion';

            export const Main: React.FC = () => {
              const frame = useCurrentFrame();
              const { fps } = useVideoConfig();
              const scale = spring({ frame, fps, config: { damping: 12 } });
              const opacity = interpolate(frame, [0, 20], [0, 1], { extrapolateRight: 'clamp' });
              return (
                <AbsoluteFill style={{ backgroundColor: '#05070f', justifyContent: 'center', alignItems: 'center' }}>
                  <h1 style={{ color: '#00e5ff', fontSize: 110, textAlign: 'center', transform: `scale(§{scale})`, opacity }}>
                    $title
                  </h1>
                </AbsoluteFill>
              );
            };
        """))
        return b
    }

    private fun ffmpeg(n: String, d: String): FileBundle {
        val b = FileBundle()
        b.add("README.md", "# $n (FFmpeg)\n\n$d\n$VIDEO_NOTE\nFFmpeg is free, open-source command line software (ffmpeg.org). Put your clips in `input/`, run a script from `scripts/`, find results in `output/`.\n\n## Scripts\n- `trim.sh in.mp4 00:00:05 00:00:15 out.mp4`\n- `concat.sh out.mp4 a.mp4 b.mp4 ...`\n- `add_audio.sh video.mp4 music.mp3 out.mp4`\n- `subtitles.sh video.mp4 subs.srt out.mp4`\n- `gif.sh in.mp4 out.gif`\n- `compress.sh in.mp4 out.mp4`\n\nOn Windows run the commands inside the scripts by hand or use WSL / Git Bash. Review each script before running it.\n")
        b.add("input/README.txt", "Put source videos, audio and subtitles here.\n")
        b.add("output/README.txt", "Results are written here.\n")
        b.add("scripts/trim.sh", t("""
            #!/usr/bin/env bash
            set -euo pipefail
            # usage: trim.sh input start end output
            ffmpeg -i "§1" -ss "§2" -to "§3" -c:v libx264 -c:a aac "§4"
        """))
        b.add("scripts/concat.sh", t("""
            #!/usr/bin/env bash
            set -euo pipefail
            # usage: concat.sh output clip1 clip2 ...   (clips must share codec/size)
            out="§1"; shift
            list=§(mktemp)
            for f in "§@"; do echo "file '§(realpath "§f")'" >> "§list"; done
            ffmpeg -f concat -safe 0 -i "§list" -c copy "§out"
            rm -f "§list"
        """))
        b.add("scripts/add_audio.sh", t("""
            #!/usr/bin/env bash
            set -euo pipefail
            # usage: add_audio.sh video audio output
            ffmpeg -i "§1" -i "§2" -map 0:v -map 1:a -c:v copy -c:a aac -shortest "§3"
        """))
        b.add("scripts/subtitles.sh", t("""
            #!/usr/bin/env bash
            set -euo pipefail
            # usage: subtitles.sh video subs.srt output   (burns subtitles into the picture)
            ffmpeg -i "§1" -vf "subtitles='§2'" -c:a copy "§3"
        """))
        b.add("scripts/gif.sh", t("""
            #!/usr/bin/env bash
            set -euo pipefail
            # usage: gif.sh input output.gif
            ffmpeg -i "§1" -vf "fps=12,scale=480:-1:flags=lanczos" "§2"
        """))
        b.add("scripts/compress.sh", t("""
            #!/usr/bin/env bash
            set -euo pipefail
            # usage: compress.sh input output  (smaller file, good quality)
            ffmpeg -i "§1" -c:v libx264 -crf 28 -preset medium -c:a aac -b:a 128k "§2"
        """))
        return b
    }

    private fun moviepy(n: String, d: String): FileBundle {
        val b = FileBundle(); val title = n.replace("\\", " ").replace("\"", "'")
        b.add("README.md", "# $n (MoviePy)\n\n$d\n$VIDEO_NOTE\nMoviePy is a free, open-source Python video editing library (MIT license). It needs FFmpeg installed.\n\n## Run\n```\npython -m venv .venv && source .venv/bin/activate\npip install -r requirements.txt\npython main.py\n```\nThe result is written to `output/video.mp4`. Edit `config.json` and `main.py`.\n\nTested against the MoviePy 2.x API (`from moviepy import ...`). If you use 1.x, import from `moviepy.editor`.\n")
        b.add("requirements.txt", "moviepy>=2.0\n")
        b.add("config.json", "{\n  \"title\": \"$title\",\n  \"width\": 1080,\n  \"height\": 1920,\n  \"duration\": 5,\n  \"fps\": 24,\n  \"background\": [5, 7, 15],\n  \"font_path\": \"\"\n}\n")
        b.add("main.py", t("""
            import json
            from pathlib import Path
            from moviepy import ColorClip, CompositeVideoClip, TextClip

            cfg = json.loads(Path("config.json").read_text())
            Path("output").mkdir(exist_ok=True)

            background = ColorClip(size=(cfg["width"], cfg["height"]), color=tuple(cfg["background"]), duration=cfg["duration"])
            text_args = dict(text=cfg["title"], font_size=90, color="white", size=(cfg["width"] - 120, None), method="caption")
            if cfg.get("font_path"):  # MoviePy 2 needs a font file path on some systems
                text_args["font"] = cfg["font_path"]
            title = TextClip(**text_args).with_duration(cfg["duration"]).with_position("center")

            CompositeVideoClip([background, title]).write_videofile("output/video.mp4", fps=cfg["fps"])
        """))
        b.add("assets/README.txt", "Put images, audio and clips here.\n")
        return b
    }

