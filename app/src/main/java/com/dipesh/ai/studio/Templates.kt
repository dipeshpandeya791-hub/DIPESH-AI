    // ------------------------------------------------------------------ Agent
    fun agent(name: String, goal: String): FileBundle {
        val n = safeText(name).ifBlank { "My Agent" }; val g = safeText(goal).ifBlank { "Help the user complete small tasks." }
        val b = FileBundle()
        b.add("README.md", t("""
            # $n

            $g

            A small, readable agent skeleton: **plan -> act -> observe** loop, a tool registry, human approval for
            sensitive tools, and a rule-based fallback so it works without any AI key.

            ## Structure
            ```
            main.py                 entry point
            src/agent/agent.py      the agent loop
            src/agent/planner.py    chooses the next step (rule-based or LLM)
            src/agent/tools.py      Tool interface + registry + example tools
            src/agent/safety.py     approval + safe path checks
            src/agent/config.py     settings from environment variables
            tests/test_agent.py     unit tests
            ```

            ## Run
            ```
            python -m venv .venv && source .venv/bin/activate
            pip install -r requirements.txt
            cp .env.example .env
            python main.py "say hello"
            pytest
            ```
            ## Optional AI
            Set `GEMINI_API_KEY` in `.env` to use Gemini (free tier has quotas). Without it the rule-based planner is used.
        """) + SAFETY)
        b.add("requirements.txt", "pytest>=7.0\nrequests>=2.31\npython-dotenv>=1.0\n")
        b.add(".env.example", "# Placeholders only. Never commit real keys.\nGEMINI_API_KEY=your-key-here\nAGENT_MAX_STEPS=6\nAGENT_WORKDIR=./workspace\n")
        b.add(".gitignore", ".env\n.venv/\n__pycache__/\nworkspace/\n")
        b.add("main.py", t("""
            import sys
            from src.agent.agent import Agent
            from src.agent.config import load_config

            def main() -> None:
                goal = " ".join(sys.argv[1:]) or "say hello"
                agent = Agent(load_config())
                print(agent.run(goal))

            if __name__ == "__main__":
                main()
        """))
        b.add("src/__init__.py", ""); b.add("src/agent/__init__.py", "")
        b.add("src/agent/config.py", t("""
            import os
            from dataclasses import dataclass

            @dataclass
            class Config:
                api_key: str = ""
                max_steps: int = 6
                workdir: str = "./workspace"

            def load_config() -> Config:
                try:
                    from dotenv import load_dotenv
                    load_dotenv()
                except ImportError:
                    pass
                return Config(
                    api_key=os.getenv("GEMINI_API_KEY", ""),
                    max_steps=int(os.getenv("AGENT_MAX_STEPS", "6")),
                    workdir=os.getenv("AGENT_WORKDIR", "./workspace"),
                )
        """))
        b.add("src/agent/safety.py", t("""
            from pathlib import Path

            def approve(action: str) -> bool:
                '''Human approval gate. Replace input() with a UI prompt if you build a GUI.'''
                return input(f"Allow: {action}? [y/N] ").strip().lower() == "y"

            def safe_path(workdir: str, relative: str) -> Path:
                '''Resolve a path and refuse anything outside workdir (blocks ../ tricks).'''
                base = Path(workdir).resolve()
                target = (base / relative).resolve()
                if base != target and base not in target.parents:
                    raise ValueError("Path escapes the working folder")
                return target
        """))
        b.add("src/agent/tools.py", t("""
            from dataclasses import dataclass
            from typing import Callable, Dict
            from .safety import approve, safe_path

            @dataclass
            class Tool:
                name: str
                description: str
                run: Callable[[str], str]
                sensitive: bool = False  # sensitive tools need human approval

            class Registry:
                def __init__(self) -> None:
                    self._tools: Dict[str, Tool] = {}

                def register(self, tool: Tool) -> None:
                    if tool.name in self._tools:
                        raise ValueError(f"duplicate tool: {tool.name}")
                    self._tools[tool.name] = tool

                def get(self, name: str) -> Tool:
                    return self._tools[name]

                def describe(self) -> str:
                    return "\n".join(f"- {t.name}: {t.description}" for t in self._tools.values())

            def build_registry(workdir: str) -> Registry:
                r = Registry()
                r.register(Tool("echo", "Repeat the input text", lambda s: s))
                def read_file(rel: str) -> str:
                    return safe_path(workdir, rel).read_text()[:2000]
                r.register(Tool("read_file", "Read a text file inside the workspace", read_file))
                def write_file(arg: str) -> str:
                    rel, _, text = arg.partition("::")
                    safe_path(workdir, rel).write_text(text)
                    return f"wrote {rel}"
                r.register(Tool("write_file", "Write 'path::text' inside the workspace", write_file, sensitive=True))
                return r
        """))
        b.add("src/agent/planner.py", t("""
            import json, os
            from typing import Optional, Tuple

            Step = Tuple[str, str]  # (tool name, input) or ("finish", answer)

            def rule_based(goal: str, history: list) -> Step:
                if history:
                    return ("finish", f"Done. Last result: {history[-1][2]}")
                low = goal.lower()
                if low.startswith("read "):
                    return ("read_file", goal[5:].strip())
                return ("echo", goal)

            def llm_plan(goal: str, history: list, tools_text: str, api_key: str) -> Optional[Step]:
                '''Optional Gemini planner. Returns None on any problem so the caller falls back.'''
                try:
                    import requests
                    prompt = (
                        "You are a careful agent. Tools:\n" + tools_text +
                        "\nGoal: " + goal + "\nHistory: " + json.dumps(history) +
                        '\nReply ONLY with JSON {"tool": name or "finish", "input": text}.'
                    )
                    url = "https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash:generateContent"
                    r = requests.post(url, params={"key": api_key}, timeout=30,
                                      json={"contents": [{"parts": [{"text": prompt}]}]})
                    r.raise_for_status()
                    text = r.json()["candidates"][0]["content"]["parts"][0]["text"]
                    data = json.loads(text[text.index("{"): text.rindex("}") + 1])
                    return (str(data["tool"]), str(data.get("input", "")))
                except Exception:
                    return None
        """))
        b.add("src/agent/agent.py", t("""
            from .config import Config
            from .planner import llm_plan, rule_based
            from .safety import approve
            from .tools import build_registry

            class Agent:
                def __init__(self, config: Config) -> None:
                    self.config = config
                    self.tools = build_registry(config.workdir)

                def run(self, goal: str) -> str:
                    history = []  # (tool, input, result)
                    for _ in range(self.config.max_steps):
                        step = None
                        if self.config.api_key:
                            step = llm_plan(goal, history, self.tools.describe(), self.config.api_key)
                        if step is None:
                            step = rule_based(goal, history)
                        name, arg = step
                        if name == "finish":
                            return arg
                        try:
                            tool = self.tools.get(name)
                        except KeyError:
                            history.append((name, arg, "unknown tool"))
                            continue
                        if tool.sensitive and not approve(f"{tool.name}({arg[:60]})"):
                            history.append((name, arg, "denied by user"))
                            continue
                        try:
                            result = tool.run(arg)
                        except Exception as e:  # report the error and let the planner adapt
                            result = f"error: {e}"
                        history.append((name, arg, result))
                    return "Stopped: step limit reached."
        """))
        b.add("tests/test_agent.py", t("""
            import pytest
            from src.agent.agent import Agent
            from src.agent.config import Config
            from src.agent.safety import safe_path

            def test_echo_goal(tmp_path):
                agent = Agent(Config(workdir=str(tmp_path)))
                assert "hello" in agent.run("hello")

            def test_blocks_path_escape(tmp_path):
                with pytest.raises(ValueError):
                    safe_path(str(tmp_path), "../outside.txt")
        """))
        b.add("docs/SAFETY.md", "# Safety notes\n" + SAFETY + "\n- Review `src/agent/tools.py` before adding tools that touch the network, shell or files.\n")
        return b
    }

